-- 4. Preserves double-entry ledger invariants in public.wallet_transactions (balance_before, balance_after).
-- 5. Prevents double-crediting via strict database-enforced idempotency and unique constraints.
-- 6. Maintains complete backward compatibility with manual UPI deposit review (admin_review_deposit_rpc).
