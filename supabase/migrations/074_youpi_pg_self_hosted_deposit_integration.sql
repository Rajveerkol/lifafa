-- ------------------------------------------------------------------------------
-- 2. CUSTOMER RPC: CREATE YOUPI DEPOSIT ORDER (SERVER-AUTHORITATIVE)
-- ------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.create_youpi_deposit_order_rpc(
    p_amount NUMERIC(12, 2),
    p_order_id TEXT,
    p_gateway_payment_id TEXT DEFAULT NULL,
    p_checkout_url TEXT DEFAULT NULL
)
RETURNS JSONB AS $$
DECLARE
    v_user_id UUID := auth.uid();
    v_clean_order_id TEXT;
    v_fee NUMERIC(12, 2);
    v_total_payable NUMERIC(12, 2);
    v_deposit_id UUID;
    v_active_upi TEXT;
BEGIN
    -- 1. Authentication check
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Authentication required to initiate deposit';
    END IF;

    -- 2. Amount boundary validation (Between ₹1.00 and ₹1,00,000.00)
    IF p_amount IS NULL OR p_amount < 1.00 OR p_amount > 100000.00 THEN
        RAISE EXCEPTION 'Deposit amount must be between ₹1.00 and ₹1,00,000.00';
    END IF;

    -- 3. Sanitize and validate order reference
    v_clean_order_id := TRIM(p_order_id);
    IF v_clean_order_id IS NULL OR LENGTH(v_clean_order_id) < 5 OR LENGTH(v_clean_order_id) > 64 THEN
        RAISE EXCEPTION 'Invalid order reference format';
    END IF;

    -- 4. Check for duplicate order ID
    IF EXISTS (SELECT 1 FROM public.deposit_requests WHERE gateway_order_id = v_clean_order_id) THEN
        RAISE EXCEPTION 'Order ID % already exists. Duplicate order creation prevented.', v_clean_order_id;
    END IF;

    -- 5. Calculate authoritative 2% platform fee
    -- Formula: Deposit Fee = Deposit Amount * 2%, Total Payable = Deposit Amount + Fee
    -- Wallet Credit = Exact Deposit Amount
    v_fee := ROUND(p_amount * 0.02, 2);
    v_total_payable := p_amount + v_fee;

    -- 6. Fetch receiving UPI ID
    SELECT value INTO v_active_upi
    FROM public.platform_settings
    WHERE key = 'DEPOSIT_UPI_ID';

    IF v_active_upi IS NULL OR TRIM(v_active_upi) = '' THEN
        v_active_upi := 'createlifafa@upi';
    END IF;

    -- 7. Insert pending deposit order
    INSERT INTO public.deposit_requests (
        user_id,
        amount,
        deposit_fee,
        total_payable,
        upi_id,
        status,
        gateway_provider,
        gateway_order_id,
        gateway_payment_id,
        checkout_url
    ) VALUES (
        v_user_id,
        p_amount,
        v_fee,
        v_total_payable,
        v_active_upi,
        'PENDING',
        'YOUPI_PG',
        v_clean_order_id,
        p_gateway_payment_id,
        p_checkout_url
    )
    RETURNING id INTO v_deposit_id;

    RETURN jsonb_build_object(
        'success', TRUE,
        'deposit_id', v_deposit_id,
        'order_id', v_clean_order_id,
        'deposit_amount', p_amount,
        'deposit_fee', v_fee,
        'total_payable', v_total_payable,
        'total_payable_paise', (v_total_payable * 100)::BIGINT,
        'status', 'PENDING'
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp;

REVOKE ALL ON FUNCTION public.create_youpi_deposit_order_rpc(NUMERIC, TEXT, TEXT, TEXT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.create_youpi_deposit_order_rpc(NUMERIC, TEXT, TEXT, TEXT) TO authenticated, service_role;

-- ------------------------------------------------------------------------------
-- 3. ATOMIC CREDIT RPC: AUTHORITATIVE YOUPI-PG / GMAIL VERIFIED DEPOSIT
-- ------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.credit_verified_youpi_deposit_rpc(
    p_gateway_order_id TEXT,
    p_utr_number TEXT,
    p_paid_amount NUMERIC(12, 2),
    p_gateway_payment_id TEXT DEFAULT NULL,
    p_verification_source TEXT DEFAULT 'YOUPI_WEBHOOK',
    p_verification_level INTEGER DEFAULT 1,
    p_gmail_message_id TEXT DEFAULT NULL,
    p_raw_payload JSONB DEFAULT '{}'::jsonb
)
RETURNS JSONB AS $$
DECLARE
    v_deposit RECORD;
    v_wallet RECORD;
    v_balance_before NUMERIC(12, 2);
    v_balance_after NUMERIC(12, 2);
    v_clean_utr TEXT;
    v_clean_order_id TEXT;
    v_idempotency_key TEXT;
    v_expected_payable NUMERIC(12, 2);
BEGIN
    v_clean_order_id := TRIM(p_gateway_order_id);
    v_clean_utr := UPPER(TRIM(p_utr_number));

    IF v_clean_order_id IS NULL OR v_clean_order_id = '' THEN
        RAISE EXCEPTION 'Order ID is required for verification credit';
    END IF;

    -- 1. Pessimistic Lock on the Deposit Request row
    SELECT * INTO v_deposit
    FROM public.deposit_requests
    WHERE gateway_order_id = v_clean_order_id
    FOR UPDATE;

    IF NOT FOUND THEN
        -- If order_id not found, check by gateway_payment_id if provided
        IF p_gateway_payment_id IS NOT NULL AND p_gateway_payment_id <> '' THEN
            SELECT * INTO v_deposit
            FROM public.deposit_requests
            WHERE gateway_payment_id = p_gateway_payment_id
            FOR UPDATE;
        END IF;
    END IF;

    IF v_deposit.id IS NULL THEN
        RAISE EXCEPTION 'Deposit order % not found', v_clean_order_id;
    END IF;

    -- 2. State machine idempotency check: Short-circuit if already APPROVED
    IF v_deposit.status = 'APPROVED' THEN
        RETURN jsonb_build_object(
            'success', TRUE,
            'deposit_id', v_deposit.id,
            'already_processed', TRUE,
            'status', 'APPROVED',
            'amount_credited', v_deposit.amount,
            'message', 'Deposit already approved and credited previously.'
        );
    END IF;

    -- Terminal state protection: REJECTED or EXPIRED orders cannot be credited automatically
    IF v_deposit.status IN ('REJECTED', 'FAILED') THEN
        RAISE EXCEPTION 'Deposit order % is in terminal state %. Cannot credit automatically.', v_clean_order_id, v_deposit.status;
    END IF;

    -- 3. Strict Amount Equality Invariant:
    -- Customer MUST have paid the exact total_payable amount (Principal + 2% fee)
    v_expected_payable := COALESCE(v_deposit.total_payable, v_deposit.amount);
    IF p_paid_amount IS NOT NULL AND ABS(p_paid_amount - v_expected_payable) > 0.05 THEN
        -- Flag order for manual investigation rather than crediting wrong amount
        UPDATE public.deposit_requests
        SET status = 'VERIFYING',
            admin_notes = COALESCE(admin_notes, '') || ' [Amount Mismatch: Expected ₹' || v_expected_payable::text || ', Paid ₹' || p_paid_amount::text || ']',
            updated_at = TIMEZONE('utc'::text, NOW())
        WHERE id = v_deposit.id;

        RAISE EXCEPTION 'Amount mismatch: expected ₹%, received ₹%. Held in VERIFYING for manual review.', v_expected_payable, p_paid_amount;
    END IF;

    -- 4. Duplicate UTR check across all previously APPROVED deposits
    IF v_clean_utr IS NOT NULL AND v_clean_utr <> '' THEN
        IF EXISTS (
            SELECT 1 FROM public.deposit_requests 
            WHERE utr_number = v_clean_utr 
              AND id <> v_deposit.id 
              AND status = 'APPROVED'
        ) THEN
            UPDATE public.deposit_requests
            SET status = 'VERIFYING',
                admin_notes = COALESCE(admin_notes, '') || ' [Duplicate UTR ' || v_clean_utr || ' detected across multiple deposits]',
                updated_at = TIMEZONE('utc'::text, NOW())
            WHERE id = v_deposit.id;

            RAISE EXCEPTION 'Duplicate UTR % already credited on another deposit. Held in VERIFYING.', v_clean_utr;
        END IF;
    END IF;

    -- 5. Webhook / Observer Idempotency Key
    v_idempotency_key := 'youpi_credit_' || v_deposit.id::text;
    IF EXISTS (SELECT 1 FROM public.wallet_transactions WHERE idempotency_key = v_idempotency_key) THEN
        RETURN jsonb_build_object(
            'success', TRUE,
            'deposit_id', v_deposit.id,
            'already_processed', TRUE,
            'message', 'Ledger transaction already exists. Duplicate credit prevented.'
        );
    END IF;

    -- 6. Pessimistic Concurrency Lock on Authoritative User Wallet
    SELECT * INTO v_wallet
    FROM public.wallets
    WHERE user_id = v_deposit.user_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'User wallet not found for user %', v_deposit.user_id;
    END IF;

    v_balance_before := v_wallet.available_balance;
    v_balance_after := v_balance_before + v_deposit.amount;

    -- 7. Credit Authoritative Wallet (Exact Deposit Amount)
    UPDATE public.wallets
    SET available_balance = v_balance_after,
        total_deposited = total_deposited + v_deposit.amount,
        updated_at = TIMEZONE('utc'::text, NOW())
    WHERE id = v_wallet.id;

    -- 8. Double-Entry Ledger Transaction Insertion
    INSERT INTO public.wallet_transactions (
        user_id,
        wallet_id,
        amount,
        type,
        status,
        reference_type,
        reference_id,
        idempotency_key,
        balance_before,
        balance_after,
        metadata
    ) VALUES (
        v_deposit.user_id,
        v_wallet.id,
        v_deposit.amount,
        'CREDIT'::transaction_type,
        'SUCCESS'::transaction_status,
        'YOUPI_PG_DEPOSIT',
        v_deposit.id::text,
        v_idempotency_key,
        v_balance_before,
        v_balance_after,
        jsonb_build_object(
            'order_id', v_clean_order_id,
            'gateway_payment_id', COALESCE(p_gateway_payment_id, v_deposit.gateway_payment_id),
            'utr_number', v_clean_utr,
            'paid_amount', p_paid_amount,
            'deposit_amount', v_deposit.amount,
            'deposit_fee', v_deposit.deposit_fee,
            'total_payable', v_deposit.total_payable,
            'verification_source', p_verification_source,
            'verification_level', p_verification_level,
            'gmail_message_id', p_gmail_message_id,
            'raw_payload', p_raw_payload
        )
    );

    -- 9. Finalize Deposit Request as APPROVED
    UPDATE public.deposit_requests
    SET status = 'APPROVED',
        utr_number = COALESCE(v_clean_utr, utr_number),
        gateway_payment_id = COALESCE(p_gateway_payment_id, gateway_payment_id),
        verification_source = p_verification_source,
        verification_level = p_verification_level,
        gmail_message_id = COALESCE(p_gmail_message_id, gmail_message_id),
        processed_at = TIMEZONE('utc'::text, NOW()),
        updated_at = TIMEZONE('utc'::text, NOW())
    WHERE id = v_deposit.id;

    -- 10. Customer In-App Notification
    INSERT INTO public.notifications (user_id, title, message, type, reference_id)
    VALUES (
        v_deposit.user_id,
        'Deposit Confirmed! ₹' || v_deposit.amount::text,
        'Your UPI payment of ₹' || v_deposit.total_payable::text || ' (UTR: ' || COALESCE(v_clean_utr, 'Verified') || ') has been verified and ₹' || v_deposit.amount::text || ' is now available in your wallet.',
        'SYSTEM',
        v_deposit.id::text
    );

    RETURN jsonb_build_object(
        'success', TRUE,
        'deposit_id', v_deposit.id,
        'order_id', v_clean_order_id,
        'amount_credited', v_deposit.amount,
        'fee_deducted', v_deposit.deposit_fee,
        'total_paid', v_deposit.total_payable,
        'utr_number', v_clean_utr,
        'balance_before', v_balance_before,
        'balance_after', v_balance_after,
        'status', 'APPROVED'
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp;

REVOKE ALL ON FUNCTION public.credit_verified_youpi_deposit_rpc(TEXT, TEXT, NUMERIC, TEXT, TEXT, INTEGER, TEXT, JSONB) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.credit_verified_youpi_deposit_rpc(TEXT, TEXT, NUMERIC, TEXT, TEXT, INTEGER, TEXT, JSONB) TO service_role;
